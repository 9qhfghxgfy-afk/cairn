#!/usr/bin/env bash
# ATS guard. Policy (decision 2026-11-15, superseding the 2026-11-14 "HTTPS only" rule):
# the shipped Info.plist carries EXACTLY ONE ATS key — NSAllowsLocalNetworking = true — and
# nothing else.
#
# Why that key, and why it does not weaken the app:
#  - Apple's own scope. ATS "applies only to connections made to public host names", and the
#    system gives no ATS protection to "Internet protocol (IP) addresses, Unqualified host
#    names, Local hosts employing the .local top-level domain" (Cocoa Keys, "Availability of
#    ATS for Remote and Local Connections"). A LAN or VPN inference server addressed by IP is
#    therefore reachable over http with NO exception at all — the old claim that an IP literal
#    was unreachable was wrong.
#  - NSAllowsLocalNetworking covers what ATS *does* police: a .local or unqualified host NAME.
#    Apple also states that when it is YES, ATS ignores NSAllowsArbitraryLoads and uses that
#    key's default of NO. Declaring it therefore narrows this app's ATS posture.
#  - Public-internet profiles still require https. That rule lives in code
#    (NetworkClass.allowsPlaintext + ServerProfile validation), where it is unit-tested, rather
#    than in a per-host ATS hole.
#
# So this guard FAILS on: the key being absent or not true (silent loss of .local reach);
# NSAllowsArbitraryLoads in any form; and NSExceptionDomains (a per-host hole is never needed).
set -euo pipefail

cd "$(dirname "$0")/.."

FAIL=0

PLIST='App/Info.plist'   # generated by `xcodegen generate` from project.yml; not tracked
SPEC='project.yml'

# Match only real keys, never prose: a comment that merely *names* a banned key must not
# fail the build, and a comment that names the permitted key must not satisfy the guard.
# YAML keys start a line (optionally indented); plist keys are <key>…</key> elements.
require_local_networking() {
  local file="$1" label="$2" ok=0
  if [[ "$file" == "$SPEC" ]]; then
    grep -Eq '^[[:space:]]*NSAllowsLocalNetworking:[[:space:]]*true' "$file" && ok=1
  else
    grep -A1 '<key>NSAllowsLocalNetworking</key>' "$file" | grep -q '<true/>' && ok=1
  fi

  if [[ "$ok" -eq 1 ]]; then
    echo "ok: $label sets NSAllowsLocalNetworking = true"
  else
    echo "FAIL: $label does not set NSAllowsLocalNetworking = true."
    echo "ATS blocks a .local or unqualified host name without it."
    FAIL=1
  fi
}

# App/Info.plist is generated, so a plain checkout (the ubuntu guards job) has only the spec.
# Either way the rule is the same; the build job runs this script again after generating.
PLIST_PRESENT=0
if [[ -f "$PLIST" ]]; then
  require_local_networking "$PLIST" "the shipped Info.plist"
  PLIST_PRESENT=1
else
  echo "note: $PLIST is not generated here; checking $SPEC, which is its source of truth."
  require_local_networking "$SPEC" "$SPEC"
fi

# Any other ATS key is a blanket or per-host hole, and none of them is needed.
for key in NSAllowsArbitraryLoads NSAllowsArbitraryLoadsForMedia \
           NSAllowsArbitraryLoadsInWebContent NSExceptionDomains; do
  if grep -Eq "^[[:space:]]*${key}:" "$SPEC"; then
    echo "FAIL: $SPEC injects $key. Only NSAllowsLocalNetworking is permitted."
    FAIL=1
  fi
  if [[ "$PLIST_PRESENT" -eq 1 ]] && grep -q "<key>${key}</key>" "$PLIST"; then
    echo "FAIL: $PLIST declares $key. Only NSAllowsLocalNetworking is permitted."
    FAIL=1
  fi
done

if [[ "$FAIL" -ne 0 ]]; then
  echo "ATS guard failed"
  exit 1
fi

echo "ATS guard passed"
